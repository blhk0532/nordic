    public function run(): void
    {
        $normalizedCoordinates = [];
        foreach ($this->coordinates as $kommun => $coords) {
            $normalizedCoordinates[strtolower($kommun)] = $coords;
        }

        $kommuner = RatsitKommun::all();

        $updated = 0;
        foreach ($kommuner as $kommun) {
            $key = strtolower($kommun->kommun);

            if (isset($normalizedCoordinates[$key])) {
                $kommun->lat = $normalizedCoordinates[$key]['lat'];
                $kommun->lng = $normalizedCoordinates[$key]['lng'];
                $kommun->save();
                $updated++;
            }
        }

        $this->command->info("Updated {$updated} kommuner with coordinates.");
    }
